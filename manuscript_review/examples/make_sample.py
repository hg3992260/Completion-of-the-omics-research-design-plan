def main() -> None:
    d = Document()
    st = d.styles["Normal"]
    st.font.name = "宋体"
    st.font.size = Pt(10.5)
    for kind, text in PARAS:
        p = d.add_paragraph()
        run = p.add_run(text)
        if kind == "h1":
            run.bold = True
            run.font.size = Pt(14)
        elif kind == "h2":
            run.bold = True
            run.font.size = Pt(12)
        if kind == "h1":
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    d.save(OUT)
    print("saved:", OUT)


if __name__ == "__main__":
    main()
